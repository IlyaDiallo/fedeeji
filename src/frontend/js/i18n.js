class I18n {
    constructor() {
        this.lang = localStorage.getItem('lang') || 'fr';
    }

    setLang(lang) {
        if (translations[lang]) {
            this.lang = lang;
            localStorage.setItem('lang', lang);
            document.dispatchEvent(
                new Event('langChanged')
            );
        }
    }

    t(key) {
        return translations[this.lang][key] || key;
    }
}

const i18n = new I18n();

function t(key) {
    return i18n.t(key);
}
